"""tools/aggregate_reports.py on reports from probe --simulate and handwritten ones."""
import asyncio
import importlib.util
import os

import pytest

from rebeambox import qualify

_s = importlib.util.spec_from_file_location("aggregate_reports", os.path.join(os.path.dirname(__file__), "..", "tools", "aggregate_reports.py"))
ag = importlib.util.module_from_spec(_s)
_s.loader.exec_module(ag)


def make(tmp_path, kind, stamp):
    import datetime
    now = datetime.datetime(2026, 10, 11, 12, 0, stamp).astimezone()
    path, _ = asyncio.run(qualify.run(simulate=kind, report_dir=str(tmp_path), do_wifi=False, wait=0.3, now=now, model="niji"))
    return path


HAND = """# First contact report

```
test id (H1..H7):            H1        model: nikko        date: 2026-10-12 09:00:00 +07
command(s) run:              rebeambox probe --qualify
measured values (name, services, bytes, seconds, fps):
  name: E-badge   address: 11:22:33:xx:xx:xx   rssi: -61
  MTU: 247   data bytes per nn20 packet: 235
  transport decision: nn20
  accepted container (type 5 or type 6): Type 5 shows, type 6 black
PASS / FAIL / PARTIAL:       PARTIAL
```
"""


def test_parse_simulated_report(tmp_path):
    row = ag.parse_report(open(make(tmp_path, "nn20", 1)).read())
    assert row["Model"] == "niji" and row["Device name"] == "E-badge-SIM"
    assert row["Address (masked)"] == "AA:BB:CC:xx:xx:xx" and row["Transport"] == "nn20"
    assert row["MTU"] == "512" and row["Verdict"] == "PASS" and row["Accepted container"] == "not tested"


def test_parse_handwritten_report_with_container():
    row = ag.parse_report(HAND)
    assert (row["Model"], row["Device name"], row["MTU"], row["Verdict"]) == ("nikko", "E-badge", "247", "PARTIAL")
    assert row["Accepted container"] == "Type 5" and row["Date"].startswith("2026-10-12")


def test_non_report_is_rejected():
    assert ag.parse_report("# notes\nnothing here") is None


def test_empty_state_and_header(tmp_path):
    out = tmp_path / "matrix.md"
    assert ag.main(["--dir", str(tmp_path / "none"), "--out", str(out)]) == 0
    t = out.read_text()
    assert "(no reports yet)" in t and "Do not edit the table by hand" in t and ag.BEGIN in t and ag.END in t


def test_matrix_rows_and_idempotence(tmp_path):
    rd = tmp_path / "reports"
    rd.mkdir()
    make(rd, "nn20", 1)
    make(rd, "badge", 2)
    (rd / "first-contact-20261012-090000.md").write_text(HAND)
    (rd / "first-contact-junk.md").write_text("not a report")
    out = tmp_path / "m.md"
    assert ag.main(["--dir", str(rd), "--out", str(out)]) == 0
    first = out.read_text()
    body = [l for l in first.splitlines() if l.startswith("| ") and "Date" not in l]
    assert len(body) == 3 and "(no reports yet)" not in first
    assert any("NEO-SIM" in l and "badge" in l for l in body) and any("Type 5" in l and "PARTIAL" in l for l in body)
    assert ag.update_file(str(out), ag.collect(str(rd))[0]) is False       # idempotent: nothing changes
    assert out.read_text() == first
    ag.main(["--dir", str(rd), "--out", str(out)])
    assert out.read_text() == first


def test_text_outside_markers_is_preserved_and_table_refreshed(tmp_path):
    rd = tmp_path / "r"
    rd.mkdir()
    out = tmp_path / "m.md"
    out.write_text("intro\n\n" + ag.BEGIN + "\nold\n" + ag.END + "\n\nmy notes\n")
    (rd / "first-contact-a.md").write_text(HAND)
    ag.main(["--dir", str(rd), "--out", str(out)])
    t = out.read_text()
    assert t.startswith("intro") and t.rstrip().endswith("my notes") and "old\n" not in t and "nikko" in t


def test_pipe_in_name_is_escaped():
    assert ag.cell("a|b") == "a\\|b"


def test_committed_matrix_is_in_sync_with_empty_reports_dir():
    root = os.path.join(os.path.dirname(__file__), "..")
    rows, _ = ag.collect(os.path.join(root, "reports"))
    if rows:
        pytest.skip("local reports present; matrix is regenerated by the script, not committed from them")
    text = open(os.path.join(root, "docs", "compatibility-matrix.md")).read()
    assert ag.render_table(rows) in text
