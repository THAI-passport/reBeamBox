#!/usr/bin/env python3
"""Aggregate first-contact reports into docs/compatibility-matrix.md.

    python tools/aggregate_reports.py                      # reads reports/first-contact-*.md, updates docs/compatibility-matrix.md
    python tools/aggregate_reports.py --dir some/dir --out matrix.md

Reads the reports written by `rebeambox probe --qualify` (or handwritten ones in the same layout). A report may add a
line `accepted container: type 5` (or `type 6`) after hardware test H2; otherwise the column shows `not tested`.
The output is deterministic (no timestamps), so running it twice changes nothing. Text outside the
`<!-- matrix:begin -->` and `<!-- matrix:end -->` markers is preserved.
"""
import argparse
import glob
import os
import re
import sys

BEGIN, END = "<!-- matrix:begin -->", "<!-- matrix:end -->"
COLUMNS = ["Date", "Model", "Device name", "Address (masked)", "Transport", "MTU", "Accepted container", "Verdict", "Report"]
HEADER = """# Compatibility matrix

Generated by `python tools/aggregate_reports.py` from `reports/first-contact-*.md`. Do not edit the table by hand; rerun the script.
Each row is one first-contact report from a real badge or from `--simulate` (simulated rows have names ending in `-SIM`
and prove nothing about hardware). Addresses are masked. `Accepted container` stays `not tested` until hardware test H2
is recorded in the report. Verdicts: PASS = transport identified and the badge answered, PARTIAL = identified but silent,
FAIL = not found or no known service. Related: docs/hardware-test-v1.md, docs/hardware-recon-checklist.md.

"""


def _first(rx, text, default="?"):
    m = re.search(rx, text, re.M)
    return m.group(1).strip() if m else default


def parse_report(text):
    """Return a row dict, or None when the text is not a first-contact report."""
    vm = re.search(r"^PASS / FAIL / PARTIAL:\s*(.*)$", text, re.M)
    if not vm:
        return None
    verdict = next((w for w in ("PARTIAL", "PASS", "FAIL") if re.search(r"\b%s\b" % w, vm.group(1))), "?")
    name = _first(r"^\s*name:\s*(.*?)(?:\s{2,}address:|$)", text)
    container = _first(r"(?im)^\s*accepted container[^:\n]*:\s*(.+)$", text, "not tested")
    if container.lower().startswith("not tested"):
        container = "not tested"
    else:
        m = re.search(r"type\s*([56])", container, re.I)
        container = ("Type %s" % m.group(1)) if m else container
    mtu = _first(r"\bMTU:\s*(\d+)", text)
    return {"Date": _first(r"\bdate:\s*(.+?)\s*$", text), "Model": _first(r"\bmodel:\s*(\S+)", text),
            "Device name": name or "?", "Address (masked)": _first(r"\baddress:\s*(\S+)", text),
            "Transport": _first(r"^\s*transport decision:\s*(\w+)", text), "MTU": mtu,
            "Accepted container": container, "Verdict": verdict}


def collect(directory):
    rows, skipped = [], []
    for path in sorted(glob.glob(os.path.join(directory, "first-contact-*.md"))):
        try:
            row = parse_report(open(path, encoding="utf-8").read())
        except (OSError, UnicodeDecodeError):
            row = None
        if row is None:
            skipped.append(os.path.basename(path))
            continue
        row["Report"] = os.path.basename(path)
        rows.append(row)
    rows.sort(key=lambda r: (r["Report"],))
    return rows, skipped


def cell(v):
    return str(v).replace("|", "\\|").replace("\n", " ")


def render_table(rows):
    out = ["| " + " | ".join(COLUMNS) + " |", "|" + "---|" * len(COLUMNS)]
    if not rows:
        out.append("| (no reports yet) | - | - | - | - | - | - | - | - |")
    for r in rows:
        out.append("| " + " | ".join(cell(r[c]) for c in COLUMNS) + " |")
    return "\n".join(out)


def update_file(path, rows):
    block = BEGIN + "\n" + render_table(rows) + "\n" + END
    if os.path.exists(path):
        text = open(path, encoding="utf-8").read()
        if BEGIN in text and END in text:
            i, j = text.index(BEGIN), text.index(END) + len(END)
            new = text[:i] + block + text[j:]
        else:
            new = text.rstrip("\n") + "\n\n" + block + "\n"
    else:
        new = HEADER + block + "\n"
    changed = (not os.path.exists(path)) or open(path, encoding="utf-8").read() != new
    if changed:
        os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
        open(path, "w", encoding="utf-8").write(new)
    return changed


def main(argv=None):
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--dir", default=os.path.join(root, "reports"))
    ap.add_argument("--out", default=os.path.join(root, "docs", "compatibility-matrix.md"))
    a = ap.parse_args(argv)
    rows, skipped = collect(a.dir)
    changed = update_file(a.out, rows)
    print("%d report(s), %d skipped, %s %s" % (len(rows), len(skipped), a.out, "updated" if changed else "unchanged"))
    for s in skipped:
        print("skipped (not a first-contact report): %s" % s, file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
