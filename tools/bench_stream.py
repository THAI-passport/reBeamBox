#!/usr/bin/env python3
"""Streaming benchmark against the software badges (virtual clock, assumed link models).

Delivered fps and drops come from the pipeline with modelled transfer times (rebeambox.streaming.WIFI_MODEL, BLE_MODEL, which are
assumptions, not measurements). Encode cost is measured on this machine. Real numbers need hardware (docs/hardware-test-v1.md H4, H5).
Usage: python tools/bench_stream.py [--seconds 20] [--write docs/streaming-benchmarks.md]
"""
import argparse
import asyncio
import os
import platform
import sys
import time

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

from rebeambox import link, media, safewrite, sim, streaming, wifi  # noqa: E402


async def wifi_row(fps, detail, seconds):
    clock = streaming.VirtualClock()
    badge = sim.SimWifiBadge()
    sess = wifi.WifiSession(lambda n: wifi.SimChannel(badge, n), pace=False)
    sink = streaming.WifiSink(sess.live(), clock, streaming.WIFI_MODEL)
    src = streaming.SyntheticSource(seconds=seconds, fps=30, detail=detail)
    st = await streaming.Pipeline(src, sink, fps, True, clock).run()
    return {"target_fps": fps, "detail": detail, "sent": st.sent, "delivered_fps": round(st.sent / st.elapsed, 2) if st.elapsed else 0,
            "avg_bytes": round(st.bytes / st.sent) if st.sent else 0, "mean_quality": round(sum(st.qualities) / len(st.qualities)) if st.qualities else 0,
            "dropped_rate": st.dropped_rate, "dropped_late": st.dropped_late, "dropped_oversize": st.dropped_oversize,
            "frames_at_badge": len(badge.frames), "max_frame": max((len(f) for f in badge.frames), default=0)}


async def ble_row(segment, seconds, min_interval_s):
    clock = streaming.VirtualClock()
    gate = safewrite.Gate("bench", safewrite.Policy(True, False, True, min_interval_s, 0, 0),
                          safewrite.Store(os.path.join(os.environ.get("TMPDIR", "/tmp"), "rebeambox-bench-%d" % os.getpid())),
                          now=lambda: 1_000_000.0 + clock.now())
    up = streaming.clip_uploader(lambda: _link(), "nn20", 368, gate, lambda m: None, fast=True)
    sink = streaming.BleSegmentSink(up, clock, segment, 500, streaming.BLE_MODEL, 368)
    src = streaming.SyntheticSource(seconds=seconds, fps=10, detail=0.3)
    st = await streaming.Pipeline(src, sink, 2.0, True, clock).run()
    return {"segment_frames": segment, "min_interval_s": min_interval_s, "uploads": st.uploads, "frames_delivered": st.sent,
            "delivered_fps": round(st.sent / st.elapsed, 2) if st.elapsed else 0, "bytes": st.bytes,
            "dropped_policy": st.dropped_policy, "dropped_late": st.dropped_late, "dropped_rate": st.dropped_rate}


async def _link():
    return link.RecordingLink(sim.SimNn20())


def encode_cost(detail, n=15):
    src = streaming.SyntheticSource(seconds=n / 10.0, fps=10, detail=detail)
    imgs = [im for _, im in src.frames()]
    ctl = streaming.QualityController(wifi.MAX_JPEG)
    t0 = time.perf_counter()
    sizes = []
    for im in imgs:
        b, _ = ctl.encode(media.fit_square(im, 360, True))
        sizes.append(len(b) if b else 0)
    dt = (time.perf_counter() - t0) / len(imgs)
    return dt * 1000.0, sum(sizes) / len(sizes)


def tables(seconds):
    w = [asyncio.run(wifi_row(f, d, seconds)) for d in (0.1, 0.6) for f in (1.0, 2.0, 3.3, 5.0)]
    b = [asyncio.run(ble_row(s, seconds, mi)) for s in (3, 6, 12) for mi in (0, 30)]
    return w, b


def render(seconds):
    w, b = tables(seconds)
    L = ["# Streaming benchmarks (software badges)", "",
         "Generated by `python tools/bench_stream.py --write docs/streaming-benchmarks.md`. Related: [streaming-plan](streaming-plan.md), [safe-write](safe-write.md).", "",
         "Method: a synthetic moving test pattern (30 fps source, %d s) goes through crop, 360 px circular mask, JPEG quality control and the rate controller into the software badge, with a virtual clock. "
         "Transfer times come from the link models in `rebeambox/streaming.py`: %s; %s. **These models are assumptions, not measurements**; the Wi-Fi 300 ms spacing and the 30720 byte limit are from the app code. "
         "Hardware tests H4 and H5 replace the model numbers." % (seconds, streaming.WIFI_MODEL.name, streaming.BLE_MODEL.name), "",
         "## Wi-Fi camera mode", "",
         "| target fps | detail | frames sent | delivered fps | avg bytes | mean quality | dropped (rate) | dropped (late) | dropped (oversize) | largest frame |",
         "|---|---|---|---|---|---|---|---|---|---|"]
    for r in w:
        L.append("| %s | %s | %d | %s | %d | %d | %d | %d | %d | %d |" % (r["target_fps"], r["detail"], r["sent"], r["delivered_fps"], r["avg_bytes"],
                 r["mean_quality"], r["dropped_rate"], r["dropped_late"], r["dropped_oversize"], r["max_frame"]))
    L += ["", "Reading: the delivered rate never exceeds about 3.3 fps because the app spaces frames 300 ms apart (the pipeline keeps the same rule, [C] for the app, [I] that the badge needs it). "
          "Detail changes frame size and the quality chosen, not the rate, as long as frames fit in 30720 bytes at some quality.", "",
          "## BLE clips (nn20, type 5 container)", "",
          "| frames per clip | min interval between writes (s) | clips written | frames delivered | delivered fps | bytes | dropped (policy) | dropped (late) | dropped (rate) |",
          "|---|---|---|---|---|---|---|---|---|"]
    for r in b:
        L.append("| %d | %d | %d | %d | %s | %d | %d | %d | %d |" % (r["segment_frames"], r["min_interval_s"], r["uploads"], r["frames_delivered"], r["delivered_fps"],
                 r["bytes"], r["dropped_policy"], r["dropped_late"], r["dropped_rate"]))
    L += ["", "Reading: over BLE every clip is a flash write plus a connect and handshake, so it is a slideshow that refreshes every several seconds, not video. "
          "With the default safe-write interval (30 s) only one clip per 30 s gets through, which is the intended protection; with 0 the rate is limited by the modelled link only.", "",
          "## Encode cost on the machine that generated this file", "",
          "Platform: %s, Python %s, Pillow encode of a 360 px frame including the circular mask (measured, varies by machine)." % (platform.platform(), platform.python_version()), "",
          "| detail | ms per frame | average bytes |", "|---|---|---|"]
    for d in (0.1, 0.3, 0.6):
        ms, avg = encode_cost(d)
        L.append("| %s | %.1f | %.0f |" % (d, ms, avg))
    L += ["", "A phone encodes in hardware or with libjpeg-turbo, so this is an upper bound for a desktop-class CPU; at 3 fps the budget is 330 ms per frame.", ""]
    return "\n".join(L)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--seconds", type=float, default=20.0)
    ap.add_argument("--write", metavar="FILE")
    a = ap.parse_args(argv)
    text = render(a.seconds)
    if a.write:
        with open(a.write, "w") as fh:
            fh.write(text)
        print("wrote", a.write)
    else:
        print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
